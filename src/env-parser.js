import fs from 'node:fs';
import path from 'node:path';

/**
 * Parses an environment file (.env, .env.example) and extracts defined keys.
 *
 * @param {string} content
 * @returns {Set<string>}
 */
export function parseEnvContent(content) {
  const keys = new Set();
  const lines = content.split(/\r?\n/);

  for (const line of lines) {
    const trimmed = line.trim();

    // Skip empty lines and comment lines
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }

    // Strip optional "export " prefix
    let decl = trimmed;
    if (decl.startsWith('export ')) {
      decl = decl.slice(7).trim();
    }

    // Match KEY=VALUE or KEY: VALUE
    const eqIndex = decl.indexOf('=');
    if (eqIndex !== -1) {
      const rawKey = decl.slice(0, eqIndex).trim();
      if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(rawKey)) {
        keys.add(rawKey);
      }
    }
  }

  return keys;
}

/**
 * Reads and parses an env example file from disk.
 *
 * @param {string} filePath
 * @returns {{ exists: boolean, keys: Set<string>, content: string }}
 */
export function readEnvExample(filePath) {
  const resolved = path.resolve(filePath);
  if (!fs.existsSync(resolved)) {
    return { exists: false, keys: new Set(), content: '' };
  }

  const content = fs.readFileSync(resolved, 'utf8');
  const keys = parseEnvContent(content);
  return { exists: true, keys, content };
}

/**
 * Appends missing keys to the .env.example file.
 * Creates the file if it does not exist.
 *
 * @param {string} filePath
 * @param {string[]} missingKeys
 * @returns {{ created: boolean, count: number }}
 */
export function appendMissingKeys(filePath, missingKeys) {
  if (!missingKeys || missingKeys.length === 0) {
    return { created: false, count: 0 };
  }

  const resolved = path.resolve(filePath);
  const exists = fs.existsSync(resolved);
  const sortedKeys = [...missingKeys].sort();

  if (!exists) {
    const header = '# Environment variables template\n# Generated by scan-env\n\n';
    const body = sortedKeys.map((k) => `${k}=`).join('\n') + '\n';
    fs.writeFileSync(resolved, header + body, 'utf8');
    return { created: true, count: sortedKeys.length };
  }

  const existingContent = fs.readFileSync(resolved, 'utf8');
  let newContent = existingContent;

  if (newContent.length > 0 && !newContent.endsWith('\n')) {
    newContent += '\n';
  }

  newContent += '\n# Added by scan-env\n';
  for (const key of sortedKeys) {
    newContent += `${key}=\n`;
  }

  fs.writeFileSync(resolved, newContent, 'utf8');
  return { created: false, count: sortedKeys.length };
}
